const codes: Record<string, number> = {
  INVALID_AMOUNT: 400100, AMOUNT_OVERFLOW: 400101,
  UNAUTHENTICATED: 401000, FORBIDDEN: 403000, NOT_FOUND: 404000,
  INSUFFICIENT_CAPACITY: 409100, DUPLICATE_INVOICE: 409101,
  IDEMPOTENCY_KEY_REUSED: 409102, RECONCILIATION_REQUIRED: 409103,
  RESERVATION_LIMIT: 409104, VERSION_EXHAUSTED: 409105,
  FX_UNAVAILABLE: 503100, SERVICE_UNAVAILABLE: 503000,
};
export function domainErrorCode(reason: string, status: number): number { return codes[reason] ?? status * 1000; }
